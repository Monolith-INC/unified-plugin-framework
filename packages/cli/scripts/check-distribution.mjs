// Artifact-only integration check: the same installer, CLI, bootstrap staging and payload installer users receive.
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {cp,mkdtemp,readFile,writeFile,rename} from 'node:fs/promises';
import {dirname,join,resolve} from 'node:path';
import {tmpdir} from 'node:os';
import {pathToFileURL} from 'node:url';
const output=resolve(process.argv[2] ?? 'release-assets');
const version=process.env.UPF_RELEASE_VERSION ?? '0.0.0-dev';
const project=await mkdtemp(join(tmpdir(),'upf-artifact-project-'));
const planFields={python:process.env.PYTHON ?? 'python3.12',workflows:['code-review','discovery','project-tracking','continuity','implementation','knowledge'],pluginRoots:[],steps:['cli'],knowledge:{knowledgeRoot:'knowledge',documentMode:'shared',docsRoot:'docs',vaultRoot:'docs'}};
const hosts=['codex','claude'];
const multiHostPlan={...planFields,hosts};
const legacyPlan={...planFields,host:'codex'};
const installArgs=(target,input)=>[join(output,'install.mjs'),'--version',version,'--source',join(output,'unified-plugin-framework-'+version+'.tar.gz'),'--project',target,'--input',input,'--python',planFields.python];
const install=(target,input)=>JSON.parse(execFileSync(process.execPath,installArgs(target,input),{encoding:'utf8',maxBuffer:16*1024*1024}));
const input=join(project,'plan.json');await writeFile(input,JSON.stringify(multiHostPlan));
assert.equal(install(project,input).ok,true);
const invalidInput=join(project,'invalid-plan.json');await writeFile(invalidInput,'{}');
assert.throws(()=>execFileSync(process.execPath,installArgs(project,invalidInput),{encoding:'utf8',stdio:'pipe'}),error=>error.stdout.includes('invalid-bootstrap'));
assert.equal(install(project,input).ok,true);
const legacyProject=await mkdtemp(join(tmpdir(),'upf-artifact-legacy-'));
const legacyInput=join(legacyProject,'plan.json');await writeFile(legacyInput,JSON.stringify(legacyPlan));
assert.equal(install(legacyProject,legacyInput).ok,true);
const root=join(project,'.upf-tools/distributions',version);
const importFromArchive=path=>import(pathToFileURL(join(root,path)).href);
const load=name=>importFromArchive('packages/cli/dist/'+name+'.js');
await Promise.all(['installer-wizard','install-report','installer-picker'].map(name=>importFromArchive('packages/cli/scripts/'+name+'.mjs')));
await Promise.all(['install-log','tooling-bootstrap','tooling-command','tooling-handoffs','tooling-recovery'].map(load));
const {parseBootstrap,forHost}=await load('tooling-input');
const parsed=parseBootstrap(multiHostPlan);
const legacy=parseBootstrap(legacyPlan);
assert.equal(parsed.ok,true,JSON.stringify(parsed));
assert.equal(legacy.ok,true,JSON.stringify(legacy));
assert.deepEqual(parsed.value.hosts,hosts);
assert.deepEqual(legacy.value.hosts,['codex']);
const plans=parsed.value.hosts.map(name=>forHost(parsed.value,name));
const [plan]=plans;
assert.deepEqual(forHost(legacy.value,'codex'),plan);
const host=await load('tooling-host');const runtime=await load('tooling-runtime');
const denied={fetch:async()=>assert.fail('An installed distribution must never fetch plugin repositories')};
await Promise.all(plans.map(async hostPlan=>{
 const pending=await host.pendingSources(project,hostPlan);
 assert.equal(pending.ok,true,JSON.stringify(pending));
 assert.deepEqual(pending.value,[],hostPlan.host);
}));
const {HOST_NAMES}=await load('host-names');
const servedSkills=async name=>{
 assert.equal((await runtime.installSkills(project,name)).ok,true,name);
 assert.equal(await runtime.installedSkills(project,name),true,name);
 const served=host.frameworkSkills(project,name).map(({name,source})=>({name,path:join(source,'SKILL.md'),scope:'repo'}));
 assert.equal(served.some(({name})=>name==='implement-work'),true,name);
 assert.equal(await host.frameworkSkillsMatch(project,served,name),true,name);
 assert.equal(await host.frameworkSkillsMatch(project,served.slice(1),name),false,`${name}: a framework skill the host does not serve is not ready`);
 const cached=join(await mkdtemp(join(tmpdir(),'upf-cached-')),'skill');
 await cp(dirname(served[0].path),cached,{recursive:true});await writeFile(join(cached,'SKILL.md'),'earlier release');
 assert.equal(await host.frameworkSkillsMatch(project,[{...served[0],path:join(cached,'SKILL.md')},...served.slice(1)],name),false,`${name}: a stale cached framework skill is not ready`);
};
// Distribution itself must be a directly loadable Agent Plugins v1.0.0 package with pre-assembled skills (zero raw placeholders).
const distSkill=await readFile(join(root,'skills/discover-quick/SKILL.md'),'utf8');
assert.equal(/\{\{[a-z]+\}\}/.test(distSkill),false,'distribution skills must be pre-assembled without raw template placeholders');
const distManifest=JSON.parse(await readFile(join(root,'plugin.json'),'utf8'));
assert.equal(distManifest.version,version,'distribution plugin.json version must match release version');
await HOST_NAMES.reduce((previous,name)=>previous.then(()=>servedSkills(name)),Promise.resolve());
const stageHost=async hostPlan=>{
 const staged=await host.stageDependencies(project,hostPlan,denied);
 assert.equal(staged.ok,true,JSON.stringify(staged));
 assert.equal(host.stagedBindings(project,hostPlan).ok,true,hostPlan.host);
};
await plans.reduce((previous,hostPlan)=>previous.then(()=>stageHost(hostPlan)),Promise.resolve());
assert.equal((await host.stageDependencies(project,plan,denied)).ok,true);
const manifest=JSON.parse(await readFile(join(root,'distribution.json'),'utf8'));
assert.equal(manifest.plugins.length,6);
assert.equal((await readFile(join(root,'dependencies/monolithic-agent-knowledge-store@0.4.1/scripts/query.py'),'utf8')).includes('Standalone stdlib Python 3.12+ CLI'),true);
assert.equal((await readFile(join(root,'dependencies/monolithic-code-review-toolkit@0.6.0/LICENSE'),'utf8')).length>0,true);
const relocated=join(await mkdtemp(join(tmpdir(),'upf-relocated-')),'distribution');
await cp(root,relocated,{recursive:true,verbatimSymlinks:true});
const movedHost=await import(pathToFileURL(join(relocated,'packages/cli/dist/tooling-host.js')).href);
const movedRuntime=await import(pathToFileURL(join(relocated,'packages/cli/dist/tooling-runtime.js')).href);
assert.equal(await movedRuntime.installedCli(project),false);
assert.equal((await movedRuntime.wireCli(project)).ok,true);
assert.equal(await movedRuntime.installedCli(project),true);
assert.equal((await movedHost.stageDependencies(project,plan,denied)).ok,true,'identical pins can be reused after distribution relocation');
const plugin=manifest.plugins.find(entry=>entry.plugin==='superpowers');
const skill=join(project,'.upf-tools/plugins/superpowers/source/skills/brainstorming/SKILL.md');
const original=await readFile(skill,'utf8');await writeFile(skill,`${original}\nchanged`);
assert.equal((await host.stageDependencies(project,plan,denied)).ok,false,'staged drift cannot be accepted by its marker');
await writeFile(skill,original);
const file=join(root,'dependencies',`${plugin.plugin}@${plugin.version}`,plugin.files.find(file=>file.path.endsWith('SKILL.md')).path);
await writeFile(file,'tampered');
assert.equal((await host.pendingSources(project,plan)).ok,false);
assert.equal((await host.stageDependencies(project,plan,denied)).ok,false);
await rename(join(root,'distribution.json'),join(root,'distribution.hidden'));
assert.equal((await host.pendingSources(project,plan)).ok,false);
process.stdout.write(`Artifact install, CLI, both payloads for every setup host, all six dependencies, re-entry and drift refusal passed: ${project}\n`);
