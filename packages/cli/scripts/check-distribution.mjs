// Artifact-only integration check: the same installer, CLI, bootstrap staging and payload installer users receive.
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {cp,mkdtemp,readFile,writeFile,rename} from 'node:fs/promises';
import {dirname,join,resolve} from 'node:path';
import {tmpdir} from 'node:os';
import {pathToFileURL} from 'node:url';
const output=resolve(process.argv[2] ?? 'release-assets');
const version=process.env.UPF_RELEASE_VERSION ?? '0.0.0-dev';
const project=await mkdtemp(join(tmpdir(),'upf-artifact-project-'));
const plan={host:'codex',python:process.env.PYTHON ?? 'python3.12',workflows:['code-review','discovery','project-tracking','continuity','implementation'],pluginRoots:[],steps:['cli'],knowledge:{knowledgeRoot:'knowledge',documentMode:'shared',docsRoot:'docs',vaultRoot:'docs'}};
const input=join(project,'plan.json');await writeFile(input,JSON.stringify(plan));
const args=[join(output,'install.mjs'),'--version',version,'--source',join(output,`unified-plugin-framework-${version}.tar.gz`),'--project',project,'--input',input,'--python',plan.python];
const install=()=>execFileSync(process.execPath,args,{encoding:'utf8',maxBuffer:16*1024*1024});
assert.match(install(),/"ok":true/);
const invalidInput=join(project,'invalid-plan.json');await writeFile(invalidInput,'{}');
assert.throws(()=>execFileSync(process.execPath,args.map(arg=>arg===input ? invalidInput : arg),{encoding:'utf8',stdio:'pipe'}),error=>error.stdout.includes('invalid-bootstrap'));
assert.match(install(),/"ok":true/);
const root=join(project,'.upf-tools/distributions',version);
const load=name=>import(pathToFileURL(join(root,'packages/cli/dist',`${name}.js`)).href);
const host=await load('tooling-host');const runtime=await load('tooling-runtime');
const denied={fetch:async()=>assert.fail('An installed distribution must never fetch plugin repositories')};
assert.equal((await host.pendingSources(project,plan)).ok,true);
assert.deepEqual((await host.pendingSources(project,plan)).value,[]);
const {HOST_NAMES}=await load('host-names');
const servedSkills=async name=>{
 assert.equal((await runtime.installSkills(project,name)).ok,true,name);
 assert.equal(await runtime.installedSkills(project,name),true,name);
 const served=host.frameworkSkills(project,name).map(({name,source})=>({name,path:join(source,'SKILL.md')}));
 assert.equal(served.some(({name})=>name==='unified-plugin-framework:implement-work'),true,name);
 assert.equal(host.frameworkSkillsMatch(project,served,name),true,name);
 assert.equal(host.frameworkSkillsMatch(project,served.slice(1),name),false,`${name}: a framework skill the host does not serve is not ready`);
 const cached=join(await mkdtemp(join(tmpdir(),'upf-cached-')),'skill');
 await cp(dirname(served[0].path),cached,{recursive:true});await writeFile(join(cached,'SKILL.md'),'earlier release');
 assert.equal(host.frameworkSkillsMatch(project,[{...served[0],path:join(cached,'SKILL.md')},...served.slice(1)],name),false,`${name}: a stale cached framework skill is not ready`);
};
await HOST_NAMES.reduce((previous,name)=>previous.then(()=>servedSkills(name)),Promise.resolve());
const staged=await host.stageDependencies(project,plan,denied);
assert.equal(staged.ok,true,JSON.stringify(staged));
assert.equal(host.stagedBindings(project,plan).ok,true);
assert.equal((await host.stageDependencies(project,plan,denied)).ok,true);
const manifest=JSON.parse(await readFile(join(root,'distribution.json'),'utf8'));
assert.equal(manifest.plugins.length,5);
assert.equal((await readFile(join(root,'runtimes/project-knowledge/pyproject.toml'),'utf8')).includes('upf-project-knowledge'),true);
assert.equal((await readFile(join(root,'dependencies/monolithic-code-review-toolkit@0.6.0/LICENSE'),'utf8')).length>0,true);
const relocated=join(await mkdtemp(join(tmpdir(),'upf-relocated-')),'distribution');
await cp(root,relocated,{recursive:true,verbatimSymlinks:true});
const movedHost=await import(pathToFileURL(join(relocated,'packages/cli/dist/tooling-host.js')).href);
const movedRuntime=await import(pathToFileURL(join(relocated,'packages/cli/dist/tooling-runtime.js')).href);
assert.equal(await movedRuntime.installedCli(project),false);
assert.equal((await movedRuntime.wireCli(project)).ok,true);
assert.equal(await movedRuntime.installedCli(project),true);
assert.equal((await movedHost.stageDependencies(project,plan,denied)).ok,true,'identical pins can be reused after distribution relocation');
const plugin=manifest.plugins.find(entry=>entry.plugin==='superpowers');
const skill=join(project,'.upf-tools/plugins/superpowers/source/skills/brainstorming/SKILL.md');
const original=await readFile(skill,'utf8');await writeFile(skill,`${original}\nchanged`);
assert.equal((await host.stageDependencies(project,plan,denied)).ok,false,'staged drift cannot be accepted by its marker');
await writeFile(skill,original);
const file=join(root,'dependencies',`${plugin.plugin}@${plugin.version}`,plugin.files.find(file=>file.path.endsWith('SKILL.md')).path);
await writeFile(file,'tampered');
assert.equal((await host.pendingSources(project,plan)).ok,false);
assert.equal((await host.stageDependencies(project,plan,denied)).ok,false);
await rename(join(root,'distribution.json'),join(root,'distribution.hidden'));
assert.equal((await host.pendingSources(project,plan)).ok,false);
process.stdout.write(`Artifact install, CLI, both payloads for every setup host, all five dependencies, re-entry and drift refusal passed: ${project}\n`);
