// Release boundary: read a clean published dependency; emit only reviewed public excerpts.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { selectContent } from '../packages/workflows/dist/content-view.js';
import { canonicalText, sha256 } from '../packages/compiler/dist/index.js';

const root = resolve(process.argv[2] ?? '');
const plugin = 'agile-backlog-toolkit';
const selection = (skill, path, heading, start, end) => ({plugin, skill, path, heading, start, end});
const selections = [
  selection('generate-work-item', 'references/audit-checklist.md', 'Requirement coverage', '## b) Coverage', '## c) Definition of Ready'),
  selection('enrich-work-item', 'common/workflows/enrichers/work-item-enricher.prompt.md', 'Preserve explicit technical requirements', '#### 3.1. Preservar dados técnicos', '### 4. Critérios Implícitos'),
  selection('validate-artifact', 'references/audit-checklist.md', 'Requirement coverage', '## b) Coverage', '## c) Definition of Ready'),
  selection('auto-fix-artifact', 'skills/auto-fix-artifact/SKILL.md', 'Minimum descriptive repairs', '### d) DoR Fixes', '## PHASE 4'),
  selection('decompose-backlog', 'references/decomposition-rules.md', 'Right-sized deliverables', '## The sizing rule', '## Story-point heuristic'),
  selection('decompose-backlog', 'references/audit-checklist.md', 'Requirement coverage', '## b) Coverage', '## c) Definition of Ready'),
  selection('split-story', 'skills/split-story/references/split-patterns.md', 'Workflow steps', '## Pattern 1', '## Pattern 2'),
  selection('split-story', 'skills/split-story/references/split-patterns.md', 'Business-rule branches', '## Pattern 2', '## Pattern 3'),
  selection('split-story', 'skills/split-story/references/split-patterns.md', 'Happy and unhappy paths', '## Pattern 3', '## Pattern 4'),
  selection('generate-breakdown-work-items', 'skills/generate-breakdown-work-items/references/plan-generation.md', 'Plan coverage', '### Coverage rule', '### Plan content'),
  selection('generate-breakdown-work-items', 'skills/generate-breakdown-work-items/references/atomic-tasks.md', 'Atomic tasks', '## Atomic-commit definition', '## Task list construction'),
  selection('amend-workitems', 'skills/amend-workitems/SKILL.md', 'Consolidated changes', '### 4. Build and approve one change set', 'Re-read current revisions'),
];
const files = new Map(selections.map(({path}) => [path, readFileSync(resolve(root, path), 'utf8')]));
const selected = selectContent(files, selections);
const destination = fileURLToPath(new URL('../packages/workflows/src/tracking-content.ts', import.meta.url));
const license = canonicalText(readFileSync(resolve(root, 'LICENSE'), 'utf8'));

// External process boundary: failures leave the committed content view unchanged.
switch (selected.ok) {
  case false:
    process.stderr.write(selected.problems.join('\n') + '\n');
    process.exitCode = 1;
    break;
  case true:
    writeFileSync(destination, '// Generated by scripts/build-tracking-content.mjs from the reviewed published release.\n'
      + `export const TRACKING_CONTENT = ${JSON.stringify(selected.views, null, 2)} as const;\n`
      + `export const TRACKING_LICENSE = ${JSON.stringify({plugin, skill: '*', path: 'LICENSE', heading: 'Upstream license', sourceDigest: sha256(license), content: license}, null, 2)} as const;\n`);
    process.stdout.write(`Wrote ${selected.views.length} public content selections.\n`);
    break;
}
