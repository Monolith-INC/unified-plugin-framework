// Release boundary: reuse the shared selector on a clean published dependency.
import {readFileSync, writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {selectContent} from '../packages/workflows/dist/content-view.js';
import {canonicalText, sha256} from '../packages/compiler/dist/index.js';

const root=resolve(process.argv[2] ?? '');
const plugin='superpowers';
const selection=(skill,heading,start,end)=>({plugin,skill,path:`skills/${skill}/SKILL.md`,heading,start,end});
const selections=[
  selection('executing-plans','Inline execution','Execute the plan yourself, task by task','**Why inline:**'),
  selection('executing-plans','Continuous progress','**Continuous execution:**','**Rulings, not stalls.**'),
  selection('executing-plans','Observe task checks','Every step that runs a command has an','- **The plan is wrong**'),
  selection('verification-before-completion','Match claims to evidence','## Common Failures','## Red Flags - STOP'),
  selection('systematic-debugging','Reproduce and locate the cause','**BEFORE attempting ANY fix:**','4. **Gather Evidence in Multi-Component Systems**'),
  selection('systematic-debugging','Test the cause minimally','### Phase 3: Hypothesis and Testing','### Phase 4: Implementation'),
];
const files=new Map(selections.map(({path})=>[path,readFileSync(resolve(root,path),'utf8')]));
const selected=selectContent(files,selections);
const license=canonicalText(readFileSync(resolve(root,'LICENSE'),'utf8'));
const destination=fileURLToPath(new URL('../packages/workflows/src/implementation-content.ts',import.meta.url));
switch(selected.ok){
  case false:
    process.stderr.write(selected.problems.join('\n')+'\n');
    process.exitCode=1;
    break;
  case true:
    writeFileSync(destination,'// Generated by scripts/build-implementation-content.mjs from the reviewed published release.\n'
      +`export const IMPLEMENTATION_CONTENT = ${JSON.stringify([...selected.views,{plugin,skill:'*',path:'LICENSE',heading:'Upstream license',sourceDigest:sha256(license),content:license}],null,2)} as const;\n`);
    process.stdout.write(`Wrote ${selected.views.length} public content selections.\n`);
    break;
}
